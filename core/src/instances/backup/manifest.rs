//! `backup_manifest.json`: the record that turns a folder of copied files into
//! a backup (F-113).
//!
//! The reader is deliberately tolerant about *unknown* keys (the file is meant
//! to survive a newer app on another machine) and strict about everything that
//! decides what gets written back: the schema prefix, the entry digest, and
//! the per-entry source. Backups made by the old application carry a different
//! schema and are refused, not guessed (ADR 0007 §5).

use std::path::Path;

use serde::{Deserialize, Serialize};
use sha2::Digest;

/// Schema of a backup this build writes and reads.
pub const BACKUP_SCHEMA: &str = "mm.instance_backup.v1";
/// The schema prefix every supported backup starts with.
pub const BACKUP_SCHEMA_PREFIX: &str = "mm.instance_backup.v";
/// The old application's prefix. Its manifests are listed but never restored:
/// group-level rows with no hashes are not a description of files.
pub const LEGACY_SCHEMA_PREFIX: &str = "modrinth_bulk_downloader.profile_update_backup.";

/// The same cap as `profile.json` and the journal: a metadata file this large
/// is already broken.
pub const MAX_MANIFEST_BYTES: u64 = 4 * 1024 * 1024;

/// Where an entry came from — and, at restore time, the only thing that
/// decides where it goes (ADR 0007 §6-5).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum EntrySource {
    ProfileJson,
    InstalledMods,
    Mods,
    Config,
    Saves,
    Lock,
}

impl EntrySource {
    pub fn as_str(self) -> &'static str {
        match self {
            EntrySource::ProfileJson => "profile_json",
            EntrySource::InstalledMods => "installed_mods",
            EntrySource::Mods => "mods",
            EntrySource::Config => "config",
            EntrySource::Saves => "saves",
            EntrySource::Lock => "lock",
        }
    }

    /// The name of the folder or file inside `content_root`. This is the fixed
    /// map a restore target is derived from; a manifest path never wins over
    /// it.
    pub fn group_name(self) -> &'static str {
        match self {
            EntrySource::ProfileJson => "profile.json",
            EntrySource::InstalledMods => "installed_mods.json",
            EntrySource::Mods => "mods",
            EntrySource::Config => "config",
            EntrySource::Saves => "saves",
            EntrySource::Lock => "instance.lock.json",
        }
    }

    /// The restore target. The only function that is allowed to answer this.
    pub fn target_of(self, content_root: &Path) -> std::path::PathBuf {
        content_root.join(self.group_name())
    }

    pub fn is_dir(self) -> bool {
        matches!(
            self,
            EntrySource::Mods | EntrySource::Config | EntrySource::Saves
        )
    }

    /// Groups in backup order. `saves` is appended by the caller only when the
    /// request asked for it.
    pub fn backup_order() -> [EntrySource; 5] {
        [
            EntrySource::ProfileJson,
            EntrySource::InstalledMods,
            EntrySource::Mods,
            EntrySource::Config,
            EntrySource::Lock,
        ]
    }

    /// Groups in restore order: content first, ownership last (ADR 0007 §6-3).
    pub fn restore_order() -> [EntrySource; 6] {
        [
            EntrySource::Mods,
            EntrySource::Config,
            EntrySource::Saves,
            EntrySource::InstalledMods,
            EntrySource::Lock,
            EntrySource::ProfileJson,
        ]
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum EntryKind {
    File,
    Dir,
}

impl EntryKind {
    pub fn as_str(self) -> &'static str {
        match self {
            EntryKind::File => "file",
            EntryKind::Dir => "dir",
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum EntryStatus {
    Copied,
    Generated,
    Skipped,
}

impl EntryStatus {
    pub fn as_str(self) -> &'static str {
        match self {
            EntryStatus::Copied => "copied",
            EntryStatus::Generated => "generated",
            EntryStatus::Skipped => "skipped",
        }
    }

    /// Copied and generated bytes exist inside the backup; skipped ones do not.
    pub fn has_bytes(self) -> bool {
        matches!(self, EntryStatus::Copied | EntryStatus::Generated)
    }
}

/// One row per file (or per empty folder), never per group.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct BackupEntry {
    pub source: EntrySource,
    /// `/`-separated, relative to `content_root`. Display and cross-check only:
    /// the restore target comes from `source` (ADR 0007 §6-5).
    pub path: String,
    pub kind: EntryKind,
    #[serde(default)]
    pub size: u64,
    #[serde(default)]
    pub sha256: String,
    #[serde(default)]
    pub version_id: String,
    pub status: EntryStatus,
    #[serde(default)]
    pub reason_code: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct BackupManifest {
    pub schema: String,
    pub created_at: String,
    pub instance_id: String,
    #[serde(default)]
    pub instance_name: String,
    #[serde(default)]
    pub minecraft_version: Option<String>,
    #[serde(default)]
    pub loader: Option<String>,
    #[serde(default)]
    pub app_version: String,
    #[serde(default)]
    pub include_saves: bool,
    #[serde(default)]
    pub entries_sha256: String,
    pub entries: Vec<BackupEntry>,
}

impl BackupManifest {
    /// SHA-256 over the compact JSON of `entries`, field order as declared.
    /// Deterministic: the same entries always produce the same bytes.
    pub fn digest_of(entries: &[BackupEntry]) -> String {
        match serde_json::to_vec(entries) {
            Ok(bytes) => hex(sha2::Sha256::digest(&bytes)),
            // `BackupEntry` is plain data: serialising it cannot fail. An
            // empty digest fails the read-side comparison, never passes it.
            Err(_) => String::new(),
        }
    }

    /// True when the stored digest matches the entries it claims to describe.
    pub fn digest_matches(&self) -> bool {
        !self.entries_sha256.is_empty() && self.entries_sha256 == Self::digest_of(&self.entries)
    }
}

/// Why a manifest could not be used as a backup description.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum ManifestError {
    #[error("invalid backup manifest")]
    Invalid,
    #[error("the backup manifest was written by the old application and cannot be restored")]
    Legacy,
    #[error("backup schema {found:?} is newer than supported {supported:?}")]
    NewerSchema { found: String, supported: String },
    #[error("the backup manifest does not match its entries digest")]
    DigestMismatch,
    #[error("the backup manifest is missing")]
    Missing,
    #[error("the backup manifest contains a NUL byte")]
    NulByte,
    #[error("the backup manifest is {size} bytes, over the {max} byte cap")]
    TooLarge { size: u64, max: u64 },
}

/// What a folder in the backup root turned out to be.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ManifestState {
    Present,
    Missing,
    Legacy,
    Invalid,
}

impl ManifestState {
    pub fn as_str(self) -> &'static str {
        match self {
            ManifestState::Present => "present",
            ManifestState::Missing => "missing",
            ManifestState::Legacy => "legacy",
            ManifestState::Invalid => "invalid",
        }
    }
}

pub fn read_manifest(path: &Path) -> Result<BackupManifest, ManifestError> {
    let meta = match std::fs::metadata(path) {
        Ok(meta) => meta,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Err(ManifestError::Missing),
        Err(_) => return Err(ManifestError::Invalid),
    };
    if meta.len() > MAX_MANIFEST_BYTES {
        return Err(ManifestError::TooLarge {
            size: meta.len(),
            max: MAX_MANIFEST_BYTES,
        });
    }
    let bytes = std::fs::read(path).map_err(|_| ManifestError::Invalid)?;
    read_manifest_bytes(&bytes)
}

fn read_manifest_bytes(bytes: &[u8]) -> Result<BackupManifest, ManifestError> {
    if bytes.contains(&0) {
        return Err(ManifestError::NulByte);
    }
    // The schema decides before the body does: a legacy file is not "invalid
    // JSON we did not expect", it is a document we knowingly refuse.
    let probe: serde_json::Value =
        serde_json::from_slice(bytes).map_err(|_| ManifestError::Invalid)?;
    let schema = probe
        .get("schema")
        .and_then(|v| v.as_str())
        .unwrap_or_default()
        .to_string();
    if schema.starts_with(LEGACY_SCHEMA_PREFIX) {
        return Err(ManifestError::Legacy);
    }
    if let Some(digits) = schema.strip_prefix(BACKUP_SCHEMA_PREFIX) {
        if digits.parse::<u32>().map(|n| n > 1).unwrap_or(false) {
            return Err(ManifestError::NewerSchema {
                found: schema,
                supported: BACKUP_SCHEMA.to_string(),
            });
        }
    }
    if schema != BACKUP_SCHEMA {
        return Err(ManifestError::Invalid);
    }
    let manifest: BackupManifest =
        serde_json::from_slice(bytes).map_err(|_| ManifestError::Invalid)?;
    if manifest.instance_id.is_empty() {
        return Err(ManifestError::Invalid);
    }
    if !manifest.digest_matches() {
        return Err(ManifestError::DigestMismatch);
    }
    Ok(manifest)
}

/// Writes the manifest and returns the SHA-256 of the bytes written.
pub fn write_manifest(path: &Path, manifest: &BackupManifest) -> Result<String, ManifestError> {
    let mut bytes = serde_json::to_vec_pretty(manifest).map_err(|_| ManifestError::Invalid)?;
    bytes.push(b'\n');
    crate::safety::atomic::write_atomic_unique(path, &mut bytes.as_slice())
        .map_err(|_| ManifestError::Invalid)?;
    use sha2::Digest as _;
    Ok(hex(sha2::Sha256::digest(&bytes)))
}

/// SHA-256 of the manifest file as it is on disk: the token a restore carries
/// from its preview to its execution.
pub fn manifest_digest(path: &Path) -> Result<String, ManifestError> {
    // Reading through `read_manifest` first keeps "a digest of a manifest we
    // would refuse" from being a meaningful answer.
    read_manifest(path)?;
    let bytes = std::fs::read(path).map_err(|_| ManifestError::Missing)?;
    Ok(hex(sha2::Sha256::digest(&bytes)))
}

pub fn manifest_state(path: &Path) -> ManifestState {
    match read_manifest(path) {
        Ok(_) => ManifestState::Present,
        Err(ManifestError::Missing) => ManifestState::Missing,
        Err(ManifestError::Legacy) => ManifestState::Legacy,
        Err(_) => ManifestState::Invalid,
    }
}

pub fn hex(bytes: impl AsRef<[u8]>) -> String {
    bytes.as_ref().iter().map(|b| format!("{b:02x}")).collect()
}
